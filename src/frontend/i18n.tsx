const DICTS: Record<Lang, Dict> = { fa, de, en };

export function allowedLangs(mode: InstallMode | null | undefined): Lang[] {
  if (mode === 'fa') return ['fa'];
  if (mode === 'de') return ['de'];
  return ['fa', 'de', 'en'];
}

const STORAGE_KEY = 'xr.uiLang';
function readStored(): Lang | null {
  try {
    const v = localStorage.getItem(STORAGE_KEY);
    return v === 'fa' || v === 'de' || v === 'en' ? v : null;
  } catch {
    return null;
  }
}
function writeStored(l: Lang) {
  try { localStorage.setItem(STORAGE_KEY, l); } catch { /* storage unavailable */ }
}
function browserLang(): Lang {
  const n = (typeof navigator !== 'undefined' ? navigator.language : 'en').slice(0, 2).toLowerCase();
  return n === 'fa' ? 'fa' : n === 'de' ? 'de' : 'en';
}

/** Choose the effective UI language from install mode, stored choice and defaults. */
export function resolveLang(mode: InstallMode | null | undefined, serverLocale?: string | null): Lang {
  const allowed = allowedLangs(mode);
  const stored = readStored();
  if (stored && allowed.includes(stored)) return stored;
  const loc = (serverLocale ?? '').slice(0, 2) as Lang;
  if (allowed.includes(loc)) return loc;
  const b = browserLang();
  return allowed.includes(b) ? b : allowed[0]!;
}

/** Current UI language for non-React code (the API client header). */
let currentLang: Lang = 'fa';
export function getCurrentLang(): Lang { return currentLang; }

interface I18nCtx {
  lang: Lang;
  dir: 'rtl' | 'ltr';
  mode: InstallMode | null;
  allowed: Lang[];
  setLang: (l: Lang) => void;
  setMode: (m: InstallMode | null) => void;
  t: (key: MsgKey, vars?: Record<string, string | number>) => string;
  /** Translate if the key exists, else return the fallback. */
  tx: (key: string, fallback?: string) => string;
  /** Format digits for display (Persian digits in fa). */
  num: (v: number | string) => string;
  /** Format an ISO date (YYYY-MM-DD…) for display. */
  date: (iso: string | null | undefined) => string;
  locale: string;
}

const Ctx = createContext<I18nCtx | null>(null);

const FA_DIGITS = ['۰', '۱', '۲', '۳', '۴', '۵', '۶', '۷', '۸', '۹'];
export const toFaDigits = (s: string) => s.replace(/[0-9]/g, (d) => FA_DIGITS[Number(d)] ?? d);

export function I18nProvider({ initialMode, serverLocale, children }: { initialMode: InstallMode | null; serverLocale?: string | null; children: ReactNode }) {
  const [mode, setMode] = useState<InstallMode | null>(initialMode);
  const [lang, setLangState] = useState<Lang>(() => resolveLang(initialMode, serverLocale));
  const allowed = useMemo(() => allowedLangs(mode), [mode]);

  // If the install mode changes (e.g. in setup or settings), snap to an allowed language.
  useEffect(() => {
    if (!allowed.includes(lang)) setLangState(allowed[0]!);
  }, [allowed, lang]);

  const dir: 'rtl' | 'ltr' = lang === 'fa' ? 'rtl' : 'ltr';
  currentLang = lang;

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = dir;
    document.title = lang === 'fa' ? 'X-Rechnung — سیستم فاکتور' : lang === 'de' ? 'X-Rechnung — Rechnungen' : 'X-Rechnung — Invoicing';
  }, [lang, dir]);

  const setLang = useCallback((l: Lang) => {
    if (!allowedLangs(mode).includes(l)) return;
    writeStored(l);
    setLangState(l);
  }, [mode]);

  const locale = lang === 'fa' ? (mode === 'fa' ? 'fa-IR' : 'fa-IR-u-ca-gregory') : lang === 'de' ? 'de-DE' : 'en-GB';

  const value = useMemo<I18nCtx>(() => {
    const dict = DICTS[lang];
    const t = (key: MsgKey, vars?: Record<string, string | number>) => {
      let s = dict[key] ?? fa[key] ?? key;
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, lang === 'fa' ? toFaDigits(String(v)) : String(v));
      return s;
    };
    const tx = (key: string, fallback?: string) => (key in dict ? dict[key as MsgKey] : fallback ?? key);
    const num = (v: number | string) => (lang === 'fa' ? toFaDigits(String(v)) : String(v));
    const date = (iso: string | null | undefined) => {
      if (!iso) return '';
      const d = new Date(iso.length === 10 ? `${iso}T12:00:00Z` : iso);
      if (Number.isNaN(d.getTime())) return iso;
      return new Intl.DateTimeFormat(locale, { year: 'numeric', month: '2-digit', day: '2-digit', timeZone: 'Europe/Berlin' }).format(d);
    };
    return { lang, dir, mode, allowed, setLang, setMode, t, tx, num, date, locale };
  }, [lang, dir, mode, allowed, setLang, locale]);

  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18nCtx {
  const v = useContext(Ctx);
  if (!v) throw new Error('useI18n outside I18nProvider');
  return v;
}

/** Turn an API error (message + field keys) into one localized string. */
export function errorText(e: unknown, i: Pick<I18nCtx, 't' | 'tx'>): string {
  const err = e as Error & { fields?: Record<string, string>; code?: string };
  if (err.code === 'NETWORK') return i.t('common.error_network');
  const fieldMsgs = err.fields
    ? Object.entries(err.fields).map(([field, key]) => {
        const label = i.tx(`f.${field}`, i.tx(`setup.${field}`, field));
        const [k, detail] = key.includes(':') ? [key.slice(0, key.indexOf(':')), key.slice(key.indexOf(':') + 1)] : [key, ''];
        const msg = `${i.tx(`verr.${k}`, k)}${detail ? `: ${detail}` : ''}`;
        return field === '_' ? msg : `${label}: ${msg}`;
      })
    : [];
  return [err.message || i.t('common.error'), ...fieldMsgs].join(' — ');
}
